def main(argv: Sequence[str] | None = None) -> int:
    """CLI: build `report-1.html` from the evaluation and the run metadata."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--evaluation", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--narrative", type=Path, default=None)
    parser.add_argument("--ref-holdout", type=Path, default=None)
    parser.add_argument("--ref-identity", type=Path, default=None)
    parser.add_argument("--calibration", type=Path, default=None)
    parser.add_argument("--date", default="")
    args = parser.parse_args(argv)
    evaluation = json.loads(args.evaluation.read_text(encoding="utf-8"))
    calibration = (json.loads(args.calibration.read_text(encoding="utf-8"))
                   if args.calibration and args.calibration.is_file() else None)
    narrative = (args.narrative.read_text(encoding="utf-8")
                 if args.narrative and args.narrative.is_file() else "")
    document = build_html(evaluation, load_meta(args.data),
                          ref_reference(args.ref_holdout, args.ref_identity), calibration,
                          narrative, args.date)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(document, encoding="utf-8")
    print(f"report: {args.out} ({len(document) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
