"""Measurements of team G: drift, fidelity, entropy and tail mass, and the logit export for team C.

Three kinds of numbers, all against the ORIGINAL model (the only reference we have):

* **drift** `KL(p_orig || p_student)` at the scoring temperature on images the request did not
  touch: out-of-distribution natural images and the in-distribution images generated by team D;
* **fidelity** `KL(q_i || p_student(x_i))` to the per-image target (the quantity the student is
  trained to reduce), split into images already processed by the stream and images still waiting;
* **shape** of the output distribution on the exact forget images (loss mean/std against the
  pseudo-labels, entropy at T = 1 and T = 2, mass outside the top-k): the quantities the score and
  team F's flatness diagnosis are sensitive to.

`export_views` writes, for one model, the logits and pre-head features of the five views team C
uses (`extract_models.py`: same subset, same seeds), so that team C's scoring model can rank a file
without recomputing anything.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as torch_f
from numpy.typing import NDArray
from torch import Tensor, nn

from hackathon.unlearning.alterations import ALTERATIONS, random_crop_resize, strong_view
from hackathon.unlearning.constants import DEFAULT_SEED, SCORING_TEMPERATURE
from hackathon.unlearning.model import model_device, predict, preprocess
from hackathon.unlearning.proxy_eval import tempered_kl
from hackathon.unlearning.research.g_meta import per_sample_matching_kl
from hackathon.unlearning.research.g_targets import BLUR_HIGH, BLUR_LOW, entropy_nats, tail_mass

LOGGER = logging.getLogger("hackathon.unlearning.research.g")
EVAL_BATCH_SIZE = 64
EXPORT_SUBSET = 1000
EXPORT_BATCH = 32
KIT_OFFSETS = {"flip": 1, "crop": 2, "jitter": 3, "jpeg": 4}
CROP_35_AREAS = (0.33, 0.37)
STRONG_MIN_AREA = 0.35
CROP_35_OFFSET = 11
STRONG_OFFSET = 20
EXPORT_VIEWS = ("exact", "crop", "jitter", "crop_35", "strong_view")
GENERATED_CHUNK_GLOB = "chunk_*.npz"
TAIL_K = 5


@dataclass
class ProbeSet:
    """Fixed images the stream is monitored on (never trained on as retain, never re-drawn).

    Attributes:
        forget_indices: Rows of the forget set used as probe.
        forget: Their uint8 images; `targets`, `labels`, `orig_logits` align with them.
        generated / ood: Retention-like images (team D's generated set, natural images).
        orig_*: Logits of the original on each group.
        saturated: Classes the gold never saw; `siblings`: their present siblings.
    """

    forget_indices: Tensor
    forget: Tensor
    targets: Tensor
    labels: Tensor
    orig_forget: Tensor
    generated: Tensor
    orig_generated: Tensor
    ood: Tensor
    orig_ood: Tensor
    saturated: list[int]
    siblings: dict[int, list[int]]
    altered: dict[str, Tensor] = field(default_factory=dict)
    orig_altered: dict[str, Tensor] = field(default_factory=dict)


def build_probe_set(
    teacher: nn.Module,
    forget_all: Tensor,
    targets: Tensor,
    probe_indices: Tensor,
    generated: Tensor,
    ood: Tensor,
    saturated: list[int],
    siblings: dict[int, list[int]],
) -> ProbeSet:
    """Cache the original's logits on every probe group (one forward pass, done once)."""
    forget = forget_all[probe_indices]
    orig_forget = predict(teacher, forget, EVAL_BATCH_SIZE)
    altered = {
        "crop": ALTERATIONS["crop"](
            forget, torch.Generator().manual_seed(DEFAULT_SEED + KIT_OFFSETS["crop"])
        ),
        "strong": strong_view(
            forget, torch.Generator().manual_seed(DEFAULT_SEED + STRONG_OFFSET), STRONG_MIN_AREA
        ),
    }
    return ProbeSet(
        probe_indices,
        forget,
        targets[probe_indices],
        orig_forget.argmax(dim=1),
        orig_forget,
        generated,
        predict(teacher, generated, EVAL_BATCH_SIZE),
        ood,
        predict(teacher, ood, EVAL_BATCH_SIZE),
        saturated,
        siblings,
        altered,
        {name: predict(teacher, images, EVAL_BATCH_SIZE) for name, images in altered.items()},
    )


def distribution_report(
    logits: Tensor,
    labels: Tensor,
    saturated: list[int],
    siblings: dict[int, list[int]],
    tail_k: int = TAIL_K,
) -> dict[str, float]:
    """Shape of an output distribution on exact forget images (everything the score is sensitive to)."""
    loss = torch_f.cross_entropy(logits.double(), labels, reduction="none")
    p1 = torch.softmax(logits.double(), dim=1)
    p2 = torch.softmax(logits.double() / SCORING_TEMPERATURE, dim=1)
    in_saturated = torch.isin(labels, torch.tensor(saturated, dtype=torch.long))
    hits: list[float] = []
    for row in in_saturated.nonzero(as_tuple=True)[0].tolist():
        masked = logits[row].clone()
        masked[saturated] = float("-inf")
        hits.append(float(int(masked.argmax()) in siblings.get(int(labels[row]), [])))
    p_true = p1.gather(1, labels[:, None]).squeeze(1)
    return {
        "blur_share": float(((p_true > BLUR_LOW) & (p_true < BLUR_HIGH)).float().mean()),
        "sure_right_share": float((p_true >= BLUR_HIGH).float().mean()),
        "sure_wrong_share": float((p_true <= BLUR_LOW).float().mean()),
        "loss_mean": float(loss.mean()),
        "loss_std": float(loss.std(unbiased=False)),
        "entropy_t1": float(entropy_nats(p1).mean()),
        "entropy_t2": float(entropy_nats(p2).mean()),
        "tail_mass_t2": float(tail_mass(p2, tail_k).mean()),
        "accuracy_vs_pseudo_label": float((logits.argmax(dim=1) == labels).float().mean()),
        "sibling_fallback": float(np.mean(hits)) if hits else 0.0,
    }


def measure_probe(
    model: nn.Module, probe: ProbeSet, processed: Tensor | None = None
) -> dict[str, float]:
    """Drift, fidelity and shape of `model` on the probe set.

    Args:
        model: The student (its mode is set to eval; the caller restores train mode).
        probe: Fixed probe groups.
        processed: Boolean mask over `probe.forget_indices`, True for images already seen by the
            stream (None = report no processed/unprocessed split).
    """
    forget = predict(model, probe.forget, EVAL_BATCH_SIZE)
    generated = predict(model, probe.generated, EVAL_BATCH_SIZE)
    ood = predict(model, probe.ood, EVAL_BATCH_SIZE)
    fidelity = per_sample_matching_kl(probe.targets, forget)
    metrics: dict[str, float] = {
        "drift_generated_kl_t2": float(tempered_kl(probe.orig_generated, generated).mean()),
        "drift_ood_kl_t2": float(tempered_kl(probe.orig_ood, ood).mean()),
        "flip_generated": float(
            (generated.argmax(1) != probe.orig_generated.argmax(1)).float().mean()
        ),
        "flip_ood": float((ood.argmax(1) != probe.orig_ood.argmax(1)).float().mean()),
        "forget_kl_t2": float(tempered_kl(probe.orig_forget, forget).mean()),
        "fidelity_mean": float(fidelity.mean()),
        "fidelity_median": float(fidelity.median()),
    }
    in_saturated = torch.isin(probe.labels, torch.tensor(probe.saturated, dtype=torch.long))
    per_image = tempered_kl(probe.orig_forget, forget)
    metrics["forget_kl_t2_nonsat"] = float(per_image[~in_saturated].mean())
    metrics["forget_kl_t2_sat"] = (
        float(per_image[in_saturated].mean()) if in_saturated.any() else 0.0
    )
    metrics["confidence_forget"] = float(torch.softmax(forget.double(), dim=1).amax(dim=1).mean())
    generated_saturated = torch.isin(
        probe.orig_generated.argmax(dim=1), torch.tensor(probe.saturated, dtype=torch.long)
    )
    generated_kl = tempered_kl(probe.orig_generated, generated)
    metrics["drift_generated_nonsat_kl_t2"] = float(generated_kl[~generated_saturated].mean())
    for name, images in probe.altered.items():
        altered_logits = predict(model, images, EVAL_BATCH_SIZE)
        altered_loss = torch_f.cross_entropy(
            altered_logits.double(), probe.labels, reduction="none"
        )
        metrics[f"altered_{name}_loss_mean"] = float(altered_loss.mean())
        metrics[f"altered_{name}_loss_std"] = float(altered_loss.std(unbiased=False))
        metrics[f"altered_{name}_kl_t2"] = float(
            tempered_kl(probe.orig_altered[name], altered_logits).mean()
        )
    if processed is not None and bool(processed.any()):
        metrics["fidelity_processed"] = float(fidelity[processed].mean())
    if processed is not None and bool((~processed).any()):
        metrics["fidelity_unprocessed"] = float(fidelity[~processed].mean())
        metrics["forget_kl_t2_unprocessed"] = float(
            tempered_kl(probe.orig_forget[~processed], forget[~processed]).mean()
        )
    metrics.update(
        {f"shape_{k}": v for k, v in distribution_report(
            forget, probe.labels, probe.saturated, probe.siblings
        ).items()}
    )  # fmt: skip
    return metrics


def load_generated_images(chunk_dir: Path, count: int, skip_chunks: int = 0) -> Tensor:
    """First `count` images of team D's generated retain proxy (uint8 NHWC), skipping `skip_chunks` files.

    Read-only: the chunks belong to team D. Only the `images` array of each `.npz` is read.

    Raises:
        FileNotFoundError: no chunk under `chunk_dir`.
    """
    files = sorted(chunk_dir.glob(GENERATED_CHUNK_GLOB))[skip_chunks:]
    if not files:
        raise FileNotFoundError(f"no {GENERATED_CHUNK_GLOB} under {chunk_dir}")
    parts: list[Tensor] = []
    total = 0
    for path in files:
        with np.load(path) as payload:
            part = torch.from_numpy(payload["images"][: count - total].copy())
        parts.append(part)
        total += len(part)
        if total >= count:
            break
    return torch.cat(parts)


def export_subset_indices(total: int) -> Tensor:
    """Team C's evaluation subset: first 1000 of a seed-0 permutation, sorted."""
    order = torch.randperm(total, generator=torch.Generator().manual_seed(DEFAULT_SEED))
    return order[:EXPORT_SUBSET].sort().values


def build_export_views(subset: Tensor) -> dict[str, Tensor]:
    """The five views of `extract_models.py`, regenerated with the same seeds."""
    views: dict[str, Tensor] = {"exact": subset}
    for name in ("crop", "jitter"):
        generator = torch.Generator().manual_seed(DEFAULT_SEED + KIT_OFFSETS[name])
        views[name] = ALTERATIONS[name](subset, generator)
    views["crop_35"] = random_crop_resize(
        subset, torch.Generator().manual_seed(DEFAULT_SEED + CROP_35_OFFSET), *CROP_35_AREAS
    )
    views["strong_view"] = strong_view(
        subset, torch.Generator().manual_seed(DEFAULT_SEED + STRONG_OFFSET), STRONG_MIN_AREA
    )
    return views


@torch.no_grad()
def logits_and_features(model: nn.Module, images: Tensor) -> tuple[Tensor, Tensor]:
    """Logits [N, 100] and pre-head features [N, 768] on CPU, eval mode, plain fp32 (like team C)."""
    model.eval()
    device = model_device(model)
    logits: list[Tensor] = []
    features: list[Tensor] = []
    for start in range(0, len(images), EXPORT_BATCH):
        batch = preprocess(images[start : start + EXPORT_BATCH], device)
        feats = model.forward_head(model.forward_features(batch), pre_logits=True)  # type: ignore[operator]
        logits.append(model.head(feats).float().cpu())  # type: ignore[operator]
        features.append(feats.float().cpu())
    return torch.cat(logits), torch.cat(features)


def export_views(
    model: nn.Module, forget_all: Tensor, path: Path, views: dict[str, Tensor] | None = None
) -> dict[str, NDArray[np.float32]]:
    """Write team C's per-view logits/features `.npz` for `model` (atomic, skipped if it exists).

    Returns the logits of every view (`logits_<view>`, used by the caller for the shape report); an
    existing file is read back instead of recomputed, so a restarted job costs nothing.
    """
    if path.is_file():
        with np.load(path) as existing:
            return {
                f"logits_{name}": np.asarray(existing[f"logits_{name}"], dtype=np.float32)
                for name in EXPORT_VIEWS
            }
    indices = export_subset_indices(len(forget_all))
    selected = views if views is not None else build_export_views(forget_all[indices])
    payload: dict[str, NDArray[np.generic]] = {"subset_indices": indices.numpy()}
    for name in EXPORT_VIEWS:
        logits, features = logits_and_features(model, selected[name])
        payload[f"logits_{name}"] = logits.numpy()
        payload[f"feats_{name}"] = features.numpy().astype(np.float16)
    partial = path.with_name(path.name + ".partial.npz")
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(partial, **payload)  # type: ignore[arg-type]
    partial.replace(path)
    LOGGER.info("exported %s", path.name)
    return {
        f"logits_{name}": np.asarray(payload[f"logits_{name}"], dtype=np.float32)
        for name in EXPORT_VIEWS
    }
