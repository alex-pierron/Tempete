"""Concept vocabulary of the generated retain proxy.

Two sources of prompts:

* `KNOWN_CLASS_CONCEPTS`: the 45 classes that appear in the forget set, named by looking at the
  forget images grouped by the original's argmax (team D, 21/11/2026). Names are best guesses; the
  original's own verdict on the generated images (`analyze`) is what decides whether a concept
  really triggers its class.
* `PROBE_VOCABULARY`: a wide list of object nouns used to discover the 55 classes that the forget
  set never touches (their names are unknown). Each noun is generated a few times and the class
  the original picks tells which class the noun belongs to.

Scale tags choose the scene template: `S` small tabletop object, `L` large outdoor subject (boat,
bridge, building), `P` plant or natural subject.
"""

from __future__ import annotations

from collections.abc import Sequence
from enum import StrEnum


class Scale(StrEnum):
    """Scene family of a concept, used to pick settings that make sense for it."""

    SMALL = "S"
    LARGE = "L"
    PLANT = "P"


S = Scale.SMALL
L = Scale.LARGE
P = Scale.PLANT

type ConceptList = tuple[tuple[str, Scale], ...]

# Head-weight groups of the original (cosine structure of `head.weight`, team D + Lucas, 21/11):
# classes 0-59 form 14 neighbourhoods; classes 60-99 are isolated. Contiguous index ranges.
HEAD_GROUPS: tuple[tuple[int, int], ...] = (
    (0, 4),
    (5, 8),
    (9, 12),
    (13, 17),
    (18, 21),
    (22, 25),
    (26, 28),
    (29, 33),
    (34, 38),
    (39, 41),
    (42, 45),
    (46, 50),
    (51, 54),
    (55, 59),
)
"""Inclusive (first, last) class index of each neighbourhood."""

# Classes fully removed from the training set of the gold (129-130 forget images each).
FULLY_FORGOTTEN_CLASSES: tuple[int, ...] = (0, 6, 7, 8, 29, 30, 31, 33, 38)


def sister_classes(
    class_index: int, forgotten: Sequence[int] = FULLY_FORGOTTEN_CLASSES
) -> list[int]:
    """Other members of the head neighbourhood of `class_index` that the gold did see.

    Empty for the isolated classes (60-99) and for a class outside every group.
    """
    for first, last in HEAD_GROUPS:
        if first <= class_index <= last:
            return [
                other
                for other in range(first, last + 1)
                if other != class_index and other not in forgotten
            ]
    return []


